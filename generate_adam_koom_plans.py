def make_document(lesson):
    doc = Document()
    base_styles(doc)
    add_title(doc, lesson)
    add_overview(doc, lesson)
    add_course(doc, lesson)
    add_notes(doc, lesson)
    add_assessment(doc, lesson)
    add_homework_reflection(doc, lesson)
    add_footer(doc, lesson)
    core = doc.core_properties
    core.title = f"Сабак № {lesson['n']}. {lesson['topic']}"
    core.subject = "Адам жана коом предмети боюнча план-конспект"
    core.author = "Мугалим үчүн даярдалган методикалык материал"
    return doc


def safe_filename(topic):
    invalid = '<>:"/\\|?*«»'
    name = "".join("-" if c in invalid else c for c in topic)
    return " ".join(name.split()).strip(" .-")


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    files = []
    for lesson in LESSONS:
        filename = f"{lesson['n']:02d}. {safe_filename(lesson['topic'])}.docx"
        path = OUTPUT_DIR / filename
        make_document(lesson).save(path)
        files.append(path)
    with ZipFile(ZIP_PATH, "w", ZIP_DEFLATED) as archive:
        for path in files:
            archive.write(path, arcname=path.name)
    print(f"Created {len(files)} DOCX files in: {OUTPUT_DIR}")
    print(f"Created archive: {ZIP_PATH}")


if __name__ == "__main__":
    main()
